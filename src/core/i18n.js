/**
 * English / Traditional Chinese UI strings.
 * Code comments stay English. Game rules stay English internally; the view translates
 * status lines and known error messages when showing them.
 */

export const LANGS = [
  { id: 'en', label: 'English', html: 'en' },
  { id: 'zh-Hant', label: '繁體中文', html: 'zh-Hant' },
];

const KEY = 'bg_lang';
const listeners = new Set();

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'zh-Hant') return saved;
  } catch {
    /* ignore */
  }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '') || '';
  if (nav.toLowerCase().startsWith('zh')) return 'zh-Hant';
  return 'en';
}

let lang = detect();

function applyHtmlLang() {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = LANGS.find((L) => L.id === lang)?.html ?? 'en';
    document.title = t('app.title');
  }
}

export const getLang = () => lang;

export function setLang(next) {
  if (next !== 'en' && next !== 'zh-Hant') return;
  if (next === lang) return;
  lang = next;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* ignore */
  }
  applyHtmlLang();
  listeners.forEach((fn) => fn(lang));
}

export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  let s = table[key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
  return s;
}

/** Translate a server/rules English sentence when we have a matching key, else leave it. */
export function te(msg) {
  if (!msg) return '';
  let m = String(msg).match(/^Solve unlocks when (\d+) or fewer cards remain in the deck$/);
  if (m) return t('cc.err.solveUnlock', { n: m[1] });
  m = String(msg).match(/^(.+) had no straight or turn card, so they shuffled their hand back and drew again\.$/);
  if (m) return t('cc.notice.redraw', { name: m[1] });
  m = String(msg).match(/^(.+) has no straight or turn card left and skips\.$/);
  if (m) return t('cc.notice.skip', { name: m[1] });
  m = String(msg).match(/^No (straight|turn) cards left in the deck$/);
  if (m) return t('cc.err.noKindLeft', { kind: t(`cc.card.${m[1]}`) });
  return t(msg);
}

export function gameText(id, field, fallback) {
  const key = `game.${id}.${field}`;
  const got = t(key);
  return got === key ? fallback : got;
}

